#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct UpdateInfo {
    pub version: String,
    pub body: Option<String>,
    pub date: Option<String>,
    /// Trusted local discovery time used to order the notification feed.
    ///
    /// This is intentionally generated by the app instead of copied from the
    /// release manifest. A repeated check for the same version preserves the
    /// first timestamp so an old update cannot jump back to the top of Inbox.
    pub detected_at: String,
}

/// Byte-progress for an in-flight desktop-app download. `percent` is omitted
/// when the updater did not report a total size.
#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct UpdateProgress {
    pub downloaded: u64,
    pub total: Option<u64>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub percent: Option<u32>,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
#[serde(rename_all = "camelCase")]
struct UpdateInstallStarted<'a> {
    version: &'a str,
}

pub(crate) fn download_progress_percent(downloaded: u64, total: Option<u64>) -> Option<u32> {
    let total = total.filter(|size| *size > 0)?;
    Some(((downloaded.min(total) * 100) / total) as u32)
}

pub(crate) fn emit_update_download_progress(
    app: &AppHandle,
    downloaded: u64,
    total: Option<u64>,
) {
    let _ = app.emit(
        "update:progress",
        UpdateProgress {
            downloaded,
            total,
            percent: download_progress_percent(downloaded, total),
        },
    );
}

pub(crate) fn emit_update_install_started(app: &AppHandle, version: &str) {
    let _ = app.emit("update:install-started", UpdateInstallStarted { version });
}

/// Trusted updater state returned to the frontend.
///
/// `unchecked` covers startup before the first successful check and preserves
/// uncertainty after a failed check. `absent` is only written by a successful
/// latest check that confirms there is no update.
#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
#[serde(tag = "status", content = "update", rename_all = "camelCase")]
pub enum PendingUpdateStatus {
    Unchecked,
    Absent,
    Pending(UpdateInfo),
}

impl PendingUpdateStatus {
    fn pending_info(&self) -> Option<UpdateInfo> {
        match self {
            Self::Pending(info) => Some(info.clone()),
            Self::Unchecked | Self::Absent => None,
        }
    }
}

#[derive(Debug)]
struct PendingUpdateLedger {
    status: PendingUpdateStatus,
    latest_check_id: u64,
}

impl Default for PendingUpdateLedger {
    fn default() -> Self {
        Self {
            status: PendingUpdateStatus::Unchecked,
            latest_check_id: 0,
        }
    }
}

/// Stores trusted updater state and orders overlapping updater checks.
pub struct PendingUpdate(Mutex<PendingUpdateLedger>);

impl Default for PendingUpdate {
    fn default() -> Self {
        Self(Mutex::new(PendingUpdateLedger::default()))
    }
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
struct UpdateCheckTicket(u64);

#[derive(Debug, Clone, PartialEq, Eq)]
struct PendingUpdateTransition {
    status: PendingUpdateStatus,
    applied: bool,
    announce_available: bool,
    cleared_pending: bool,
}

static UPDATE_INSTALL_IN_PROGRESS: AtomicBool = AtomicBool::new(false);
static UPDATE_CHECK_SERIALIZER: tokio::sync::Mutex<()> = tokio::sync::Mutex::const_new(());
const UPDATE_CHECK_INTERVAL: Duration = Duration::from_secs(21_600);
/// Betas iterate multiple times per day, so prerelease channels re-check every
/// 30 minutes while stable keeps the 6h cadence.
const PRERELEASE_UPDATE_CHECK_INTERVAL: Duration = Duration::from_secs(1_800);
const UPDATE_SYNC_RETRY_INTERVAL: Duration = Duration::from_secs(30);
pub(crate) const UPDATE_DEFERRED_DURING_SYNC: &str = "Update deferred while a sync is active";
pub(crate) const UPDATE_DEFERRED_DURING_MUTATION: &str =
    "Update deferred while an HQ change is active";
pub(crate) const UPDATE_DEFERRED_DURING_PROCESS_EXIT: &str =
    "Update deferred while HQ processes are still stopping";

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum BackgroundUpdateAction {
    Install,
    DeferForSync,
    Announce,
}

fn install_failure_is_transient_deferral(error: &str) -> bool {
    matches!(
        error,
        UPDATE_DEFERRED_DURING_SYNC
            | UPDATE_DEFERRED_DURING_MUTATION
            | UPDATE_DEFERRED_DURING_PROCESS_EXIT
    )
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum UpdateAnnouncement {
    /// Keep the update in shared state and notify mounted app surfaces without
    /// creating a separate window.
    PersistentOnly,
    /// Also raise the compact banner/widget for users who deliberately opted
    /// out of automatic installation.
    TransientBanner,
}

fn should_raise_transient_update_surface(announcement: UpdateAnnouncement) -> bool {
    announcement == UpdateAnnouncement::TransientBanner
}

fn background_check_interval(channel: ReleaseChannel) -> Duration {
    match channel {
        ReleaseChannel::Stable => UPDATE_CHECK_INTERVAL,
        ReleaseChannel::Beta | ReleaseChannel::Alpha => PRERELEASE_UPDATE_CHECK_INTERVAL,
    }
}

fn background_update_action(
    automatic_updates: bool,
    sync_in_progress: bool,
    silent_install_supported: bool,
) -> BackgroundUpdateAction {
    match (
        automatic_updates && silent_install_supported,
        sync_in_progress,
    ) {
        (true, false) => BackgroundUpdateAction::Install,
        (true, true) => BackgroundUpdateAction::DeferForSync,
        (false, _) => BackgroundUpdateAction::Announce,
    }
}

/// Every supported desktop platform now has a safe silent-install path.
/// Windows uses `windows_update`: the minisign-verified package is staged, HQ
/// children are quiesced, and a copied signed helper waits for the parent to
/// exit before launching NSIS. This is deliberately a function rather than a
/// constant so platform policy remains explicit at each decision point.
pub(crate) fn silent_install_supported() -> bool {
    true
}

pub(crate) fn sync_in_progress() -> bool {
    crate::commands::process::is_registered("hq-sync")
        || hq_desktop_core::sync_progress::read_fresh_snapshot()
            .is_some_and(|snapshot| snapshot.status == "syncing")
}

/// Process-wide lease preventing separate app surfaces from starting the same
/// download concurrently. Dropping the lease resets the flag on every returning
/// path; a successful `app.restart()` terminates the process instead.
struct UpdateInstallGuard<'a> {
    in_progress: &'a AtomicBool,
}

impl<'a> UpdateInstallGuard<'a> {
    fn acquire(in_progress: &'a AtomicBool) -> Option<Self> {
        in_progress
            .compare_exchange(false, true, Ordering::AcqRel, Ordering::Acquire)
            .ok()
            .map(|_| Self { in_progress })
    }
}

impl Drop for UpdateInstallGuard<'_> {
    fn drop(&mut self) {
        self.in_progress.store(false, Ordering::Release);
    }
}

fn detection_timestamp() -> String {
    Utc::now().to_rfc3339_opts(SecondsFormat::Millis, true)
}

fn discovered_update(version: String, body: Option<String>, date: Option<String>) -> UpdateInfo {
    UpdateInfo {
        version,
        body,
        date,
        detected_at: detection_timestamp(),
    }
}

fn begin_check(ledger: &mut PendingUpdateLedger) -> UpdateCheckTicket {
    ledger.latest_check_id = ledger.latest_check_id.wrapping_add(1);
    UpdateCheckTicket(ledger.latest_check_id)
}

fn preserved_transition(ledger: &PendingUpdateLedger) -> PendingUpdateTransition {
    PendingUpdateTransition {
        status: ledger.status.clone(),
        applied: false,
        announce_available: false,
        cleared_pending: false,
    }
}

/// Apply a discovered update only when it belongs to the latest-started check.
///
/// Metadata may change when an endpoint republishes the same version, but its
/// original discovery time and notification identity remain stable.
#[cfg(test)]
fn apply_discovered_update(
    ledger: &mut PendingUpdateLedger,
    ticket: UpdateCheckTicket,
    discovered: UpdateInfo,
) -> PendingUpdateTransition {
    apply_discovered_update_with_authority(ledger, ticket, discovered, true)
}

fn is_prerelease_version(version: &str) -> bool {
    let version = version.strip_prefix('v').unwrap_or(version);
    semver::Version::parse(version)
        .map(|version| !version.pre.is_empty())
        .unwrap_or(false)
}

fn apply_discovered_update_with_authority(
    ledger: &mut PendingUpdateLedger,
    ticket: UpdateCheckTicket,
    mut discovered: UpdateInfo,
    authoritative: bool,
) -> PendingUpdateTransition {
    if ticket.0 != ledger.latest_check_id {
        return preserved_transition(ledger);
    }

    // A prerelease-channel resolver fallback can still discover a stable
    // update, but it cannot prove that an already-known prerelease disappeared.
    if !authoritative
        && matches!(
            &ledger.status,
            PendingUpdateStatus::Pending(existing)
                if is_prerelease_version(&existing.version)
        )
        && !is_prerelease_version(&discovered.version)
    {
        return preserved_transition(ledger);
    }

    let announce_available = match &ledger.status {
        PendingUpdateStatus::Pending(existing) if existing.version == discovered.version => {
            discovered.detected_at.clone_from(&existing.detected_at);
            false
        }
        _ => true,
    };

    ledger.status = PendingUpdateStatus::Pending(discovered);
    PendingUpdateTransition {
        status: ledger.status.clone(),
        applied: true,
        announce_available,
        cleared_pending: false,
    }
}

/// Apply a confirmed no-update result only when it belongs to the latest check.
#[cfg(test)]
fn apply_confirmed_absent(
    ledger: &mut PendingUpdateLedger,
    ticket: UpdateCheckTicket,
) -> PendingUpdateTransition {
    apply_confirmed_absent_with_authority(ledger, ticket, true)
}

fn apply_confirmed_absent_with_authority(
    ledger: &mut PendingUpdateLedger,
    ticket: UpdateCheckTicket,
    authoritative: bool,
) -> PendingUpdateTransition {
    if ticket.0 != ledger.latest_check_id || !authoritative {
        return preserved_transition(ledger);
    }

    let cleared_pending = matches!(ledger.status, PendingUpdateStatus::Pending(_));
    ledger.status = PendingUpdateStatus::Absent;
    PendingUpdateTransition {
        status: ledger.status.clone(),
        applied: true,
        announce_available: false,
        cleared_pending,
    }
}

fn begin_app_check(app: &AppHandle) -> Result<UpdateCheckTicket, String> {
    let state = app
        .try_state::<PendingUpdate>()
        .ok_or_else(|| "updater state unavailable".to_string())?;
    let mut ledger = state.0.lock().unwrap_or_else(|e| e.into_inner());
    Ok(begin_check(&mut ledger))
}

fn apply_discovered_to_app(
    app: &AppHandle,
    ticket: UpdateCheckTicket,
    discovered: UpdateInfo,
    authoritative: bool,
) -> Result<PendingUpdateTransition, String> {
    let state = app
        .try_state::<PendingUpdate>()
        .ok_or_else(|| "updater state unavailable".to_string())?;
    let mut ledger = state.0.lock().unwrap_or_else(|e| e.into_inner());
    Ok(apply_discovered_update_with_authority(
        &mut ledger,
        ticket,
        discovered,
        authoritative,
    ))
}

fn apply_absent_to_app(
    app: &AppHandle,
    ticket: UpdateCheckTicket,
    authoritative: bool,
) -> Result<PendingUpdateTransition, String> {
    let state = app
        .try_state::<PendingUpdate>()
        .ok_or_else(|| "updater state unavailable".to_string())?;
    let mut ledger = state.0.lock().unwrap_or_else(|e| e.into_inner());
    Ok(apply_confirmed_absent_with_authority(
        &mut ledger,
        ticket,
        authoritative,
    ))
}

fn apply_absent_and_emit(
    app: &AppHandle,
    ticket: UpdateCheckTicket,
    authoritative: bool,
) -> Result<PendingUpdateStatus, String> {
    let transition = apply_absent_to_app(app, ticket, authoritative)?;
    if transition.applied && transition.cleared_pending {
        let _ = app.emit("update:cleared", ());
    }
    Ok(transition.status)
}

async fn record_and_announce_update(
    app: &AppHandle,
    ticket: UpdateCheckTicket,
    discovered: UpdateInfo,
    authoritative: bool,
    announcement: UpdateAnnouncement,
) -> Result<Option<UpdateInfo>, String> {
    let transition = apply_discovered_to_app(app, ticket, discovered, authoritative)?;
    let info = transition.status.pending_info();
    if !transition.applied || !transition.announce_available {
        return Ok(info);
    }

    let info = info.expect("an applied available transition always stores update info");
    let _ = app.emit("update:available", &info);
    // Only opted-out background discovery raises a transient surface. Manual
    // checks already have a visible caller, while automatic-install recovery
    // is represented persistently in Settings, the version popout, and Inbox.
    // Opening a separate banner for either case makes the desktop look like
    // windows are flashing while the user is already working in it.
    // US-003: widget takeover must never fall back to native banners.
    if should_raise_transient_update_surface(announcement)
        && (crate::commands::banner::custom_banner_enabled()
            || crate::commands::widget::takeover_active(app))
    {
        let _ = crate::commands::banner::show_update_banner(
            app.clone(),
            info.version.clone(),
            info.body.clone(),
        )
        .await;
    }

    Ok(Some(info))
}

/// Read the user's stored channel preference from `~/.hq/menubar.json`,
/// or `None` if the file is missing / unparseable / the field is absent.
/// We deliberately do NOT propagate errors — a corrupted menubar.json
/// must never break the updater. The caller treats `None` as "no
/// preference" and lets `effective_channel` apply identity-aware
/// defaults.
fn read_stored_release_channel() -> Option<String> {
    let path = paths::menubar_json_path().ok()?;
    let contents = std::fs::read_to_string(&path).ok()?;
    let prefs: MenubarPrefs = serde_json::from_str(&contents).ok()?;
    prefs.release_channel
}

/// Resolve the per-channel updater endpoint URL the background loop and
/// on-demand command should poll. Combines the stored preference with
/// the indigo gate, then resolves to a `latest.json` URL via the
/// `release_channel` module.
async fn resolve_endpoint() -> (ReleaseChannel, ResolvedChannelEndpoint) {
    let stored = read_stored_release_channel();
    let is_indigo = feature_gate::is_indigo_user().await;
    let channel: ReleaseChannel = effective_channel(stored.as_deref(), is_indigo);
    let resolved = resolve_channel_endpoint(channel).await;
    log(
        "updater",
        &format!(
            "resolved channel={} endpoint={} provenance={:?}",
            channel.as_str(),
            resolved.url,
            resolved.provenance
        ),
    );
    (channel, resolved)
}

struct ChannelAwareUpdater {
    updater: tauri_plugin_updater::Updater,
    provenance: EndpointProvenance,
    channel: ReleaseChannel,
}

/// Build a channel-aware `tauri_plugin_updater::Updater` for this
/// invocation. Tauri's `app.updater()` always uses the static endpoint
/// from `tauri.conf.json`; `app.updater_builder()` lets us override
/// per-call so the same binary serves three channels without rebuild.
async fn channel_aware_updater(app: &AppHandle) -> Result<ChannelAwareUpdater, String> {
    let (channel, resolved) = resolve_endpoint().await;
    let endpoint =
        Url::parse(&resolved.url).map_err(|e| format!("invalid updater endpoint: {e}"))?;
    let updater = app
        .updater_builder()
        .endpoints(vec![endpoint])
        .map_err(|e| format!("updater_builder.endpoints: {e}"))?
        .build()
        .map_err(|e| format!("updater_builder.build: {e}"))?;
    Ok(ChannelAwareUpdater {
        updater,
        provenance: resolved.provenance,
        channel,
    })
}

#[tauri::command]
pub async fn check_for_updates(app: AppHandle) -> Result<Option<UpdateInfo>, String> {
    let _check_guard = UPDATE_CHECK_SERIALIZER.lock().await;
    let ticket = begin_app_check(&app)?;
    let updater = channel_aware_updater(&app).await?;
    let authoritative = updater.provenance.absence_is_authoritative();
    match updater.updater.check().await {
        Ok(Some(update)) => {
            let info = discovered_update(
                update.version.clone(),
                update.body.clone(),
                update.date.map(|d| d.to_string()),
            );
            record_and_announce_update(
                &app,
                ticket,
                info,
                authoritative,
                UpdateAnnouncement::PersistentOnly,
            )
            .await
        }
        Ok(None) => {
            // Up to date — clear any previously stored pending update so a
            // pulled/superseded release doesn't keep hydrating surfaces
            // (e.g. the version pop-out) as "Update available" forever.
            Ok(apply_absent_and_emit(&app, ticket, authoritative)?.pending_info())
        }
        Err(e) => Err(e.to_string()),
    }
}

/// Return the update the background checker (or a manual check) already
/// found, if any. Lets late-mounting surfaces — e.g. the status-bar version
/// pop-out (US-017) — hydrate "update available" state without waiting for
/// the next `update:available` event or forcing a fresh network check.
#[tauri::command]
pub fn get_pending_update(app: AppHandle) -> PendingUpdateStatus {
    app.try_state::<PendingUpdate>()
        .map(|state| {
            state
                .0
                .lock()
                .unwrap_or_else(|e| e.into_inner())
                .status
                .clone()
        })
        .unwrap_or(PendingUpdateStatus::Unchecked)
}

async fn install_verified_update(
    app: &AppHandle,
    update: &tauri_plugin_updater::Update,
) -> Result<(), String> {
    emit_update_install_started(app, &update.version);
    #[cfg(target_os = "windows")]
    {
        crate::windows_update::install_verified_update(app, update).await
    }
    #[cfg(not(target_os = "windows"))]
    {
        let mut downloaded = 0_u64;
        update
            .download_and_install(
                |chunk, total| {
                    downloaded = downloaded.saturating_add(chunk as u64);
                    emit_update_download_progress(app, downloaded, total);
                },
                || {},
            )
            .await
            .map_err(|error| error.to_string())?;
        crate::commands::hq_work::spawn_maybe_co_install_hq_work();
        app.restart();
    }
}

/// Install the newest stable release through the same single-flight and
/// platform-safe lifecycle as the normal updater. The hard version gate uses
/// this entry point so it cannot drift back to Tauri's abrupt Windows exit.
pub(crate) async fn install_stable_update(app: &AppHandle) -> Result<(), String> {
    let _install_guard = UpdateInstallGuard::acquire(&UPDATE_INSTALL_IN_PROGRESS)
        .ok_or_else(|| "An update installation is already in progress".to_string())?;
    let _check_guard = UPDATE_CHECK_SERIALIZER.lock().await;
    let updater = app.updater().map_err(|error| error.to_string())?;
    match updater.check().await {
        Ok(Some(update)) => install_verified_update(app, &update).await,
        Ok(None) => Err(
            "hq-pro hard-gate fired but tauri-updater sees no release; latest.json may be stale"
                .to_string(),
        ),
        Err(error) => Err(error.to_string()),
    }
}

#[tauri::command]
pub async fn install_update(app: AppHandle) -> Result<(), String> {
    let _install_guard = UpdateInstallGuard::acquire(&UPDATE_INSTALL_IN_PROGRESS)
        .ok_or_else(|| "An update installation is already in progress".to_string())?;
    let _check_guard = UPDATE_CHECK_SERIALIZER.lock().await;
    let ticket = begin_app_check(&app)?;

    // Note: We must call updater.check() again here because the tauri_plugin_updater::Update
    // type cannot be stored (not Clone). The PendingUpdate state only holds metadata (UpdateInfo).
    // This is an architectural constraint of the plugin, not a redundant call.
    //
    // We re-resolve the channel endpoint at install time too — if the user
    // changes their channel preference between "Check Now" and "Install",
    // we honor the latest choice. The endpoint resolution is cheap (the
    // GH API result is uncached but the next 6h check will hit it again
    // anyway) and the stable fallback path skips the network entirely.
    let updater = channel_aware_updater(&app).await?;
    let authoritative = updater.provenance.absence_is_authoritative();
    match updater.updater.check().await {
        Ok(Some(update)) => {
            let info = discovered_update(
                update.version.clone(),
                update.body.clone(),
                update.date.map(|d| d.to_string()),
            );
            let _ = record_and_announce_update(
                &app,
                ticket,
                info,
                authoritative,
                UpdateAnnouncement::PersistentOnly,
            )
            .await?;
            // Best-effort HQ Work co-install on platforms where it cannot race
            // the NSIS file swap. Windows performs only the desktop update in
            // this critical section.
            #[cfg(not(target_os = "windows"))]
            crate::commands::hq_work::spawn_maybe_co_install_hq_work();
            install_verified_update(&app, &update).await
        }
        Ok(None) => {
            let _ = apply_absent_and_emit(&app, ticket, authoritative)?;
            Err("No update available".to_string())
        }
        Err(e) => Err(e.to_string()),
    }
}

/// Tauri command returning the list of channels the user is allowed to
/// pick from. `@getindigo.ai` users see all three (stable / beta /
/// alpha); everyone else sees only stable, which makes the picker
/// degenerate into a non-interactive label — the Svelte side keys off
/// `length > 1` to decide whether to render it.
///
/// Returned in display order: stable → beta → alpha (most stable first).
#[tauri::command]
pub async fn available_channels() -> Vec<String> {
    if feature_gate::is_indigo_user().await {
        vec![
            ReleaseChannel::Stable.as_str().to_string(),
            ReleaseChannel::Beta.as_str().to_string(),
            ReleaseChannel::Alpha.as_str().to_string(),
        ]
    } else {
        vec![ReleaseChannel::Stable.as_str().to_string()]
    }
}

/// Tauri command returning `true` iff the signed-in user's email ends in
