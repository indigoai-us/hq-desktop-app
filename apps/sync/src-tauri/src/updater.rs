    #[test]
    fn pending_and_absent_wire_states_are_discriminated() {
        let pending = PendingUpdateStatus::Pending(update(
            "0.10.36",
            "Pending update",
            "2026-07-27T15:00:00.000Z",
        ));
        let pending_json = serde_json::to_value(&pending).expect("pending should serialize");
        assert_eq!(pending_json["status"], "pending");
        assert_eq!(pending_json["update"]["version"], "0.10.36");
        assert_eq!(
            serde_json::to_value(PendingUpdateStatus::Absent).expect("absent should serialize"),
            serde_json::json!({ "status": "absent" })
        );
    }

    #[test]
    fn older_available_result_cannot_overwrite_newer_confirmed_absence() {
        let mut ledger = PendingUpdateLedger::default();
        let older = begin_check(&mut ledger);
        let newer = begin_check(&mut ledger);

        let absent = apply_confirmed_absent(&mut ledger, newer);
        assert!(absent.applied);
        assert_eq!(ledger.status, PendingUpdateStatus::Absent);

        let stale = apply_discovered_update(
            &mut ledger,
            older,
            update("0.10.36", "Stale update", "2026-07-27T15:00:00.000Z"),
        );
        assert!(!stale.applied);
        assert!(!stale.announce_available);
        assert_eq!(ledger.status, PendingUpdateStatus::Absent);
    }

    #[test]
    fn older_absent_result_cannot_clear_newer_pending_update() {
        let mut ledger = PendingUpdateLedger::default();
        let older = begin_check(&mut ledger);
        let newer = begin_check(&mut ledger);

        let available = apply_discovered_update(
            &mut ledger,
            newer,
            update("0.10.37", "Newest update", "2026-07-27T16:00:00.000Z"),
        );
        assert!(available.applied);

        let stale = apply_confirmed_absent(&mut ledger, older);
        assert!(!stale.applied);
        assert!(!stale.cleared_pending);
        assert_eq!(ledger.status, available.status);
    }

