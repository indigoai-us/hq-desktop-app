function buildTable(): Map<string, string> {
  const table = new Map<string, string>();
  for (const line of RAW.split("\n")) {
    const record = line.trim();
    if (record.length === 0) continue;
    const separator = record.lastIndexOf(" ");
    if (separator <= 0) continue;
    const names = record.slice(0, separator);
    const emoji = record.slice(separator + 1);
    if (emoji.length === 0) continue;
    for (const name of names.split(",")) {
      const key = name.trim().toLowerCase();
      if (key.length > 0 && !table.has(key)) table.set(key, emoji);
    }
  }
  return table;
}

/** shortcode (without colons, lower-case) → Unicode emoji. */
export const EMOJI_SHORTCODES: ReadonlyMap<string, string> = buildTable();
