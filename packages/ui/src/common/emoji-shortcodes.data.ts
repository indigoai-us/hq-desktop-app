/**
 * Vendored `:shortcode:` → Unicode emoji table (the common Slack/GitHub set).
 *
 * WHY VENDORED. `lib/reactions.ts` already states the rule this file follows:
 * "never pull a multi-MB emoji-data dependency" into the Tauri webview. Every
 * npm shortcode package (`emoji-datasource`, `node-emoji`, `emojibase-data`)
 * ships the full Unicode inventory plus vendor sheets — hundreds of KB to
 * multiple MB of data for a lookup table we only need the popular slice of. So
 * the common set is vendored here as inert DATA: a single newline-separated
 * string of `shortcode[,alias…] emoji` records parsed once at module load.
 *
 * Names follow gemoji / Slack spelling (`:stuck_out_tongue_winking_eye:`,
 * `:+1:`, `:tada:`) because those are the forms that actually arrive on the
 * wire from Slack-relayed messages and from people who type shortcodes.
 *
 * Adding entries: append `name[,alias] <emoji>` lines. Unknown shortcodes are
 * rendered as literal text, so a missing entry is never an error.
 */

